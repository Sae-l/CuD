const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {spawnSync} = require('node:child_process');
const {pathToFileURL,fileURLToPath} = require('node:url');
const checkout = path.resolve(__dirname,'../..');
const vault = path.resolve(__dirname,'..');
const text = fs.readFileSync(path.join(vault,'30 Weiterentwicklung/30 Neue Vorlesung hinzufügen.md'),'utf8');
const sample = text.match(/```js\n([\s\S]*?)\n```/)[1];
const lesson = vm.runInNewContext('('+sample+')',{}, {timeout:1000});
for (const field of ['id','title','topic','origin','pages','goal','code','investigate','modify','make','answer']) assert(typeof lesson[field]==='string' && lesson[field].length,field);
assert(Number.isInteger(lesson.page) && lesson.page>0);
assert.equal(typeof lesson.output,'string');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(checkout,'Lernwerkzeug/inhalte.js'),'utf8'),context);
const kurs = fs.readFileSync(path.join(checkout,'Lernwerkzeug/kurs.js'),'utf8');
const marker = 'for (const [index, lesson] of vorlesungen.entries()) {';
assert(kurs.includes(marker));
vm.runInContext(kurs.replace(marker,'vorlesungen.push('+JSON.stringify(lesson)+');\n'+marker),context);
const data = JSON.parse(vm.runInContext('JSON.stringify({items:inhalte,sources:quellen,lessons:vorlesungen})',context));
assert.equal(data.lessons.length,11);
const ids = new Set(data.items.map(x=>x.id));assert.equal(ids.size,data.items.length);
const added = data.items.find(x=>x.id==='lektion-11');assert(added && added.kind==='Vorlesung');
for(const id of added.needs)assert(ids.has(id));
for(const id of added.sources){const target=new URL(data.sources[id].href,pathToFileURL(path.join(checkout,'Lernwerkzeug/index.html')));assert.equal(target.protocol,'file:');assert(fs.existsSync(fileURLToPath(target)));}
assert.equal(added.quiz.correct,0);
assert(added.quiz.options.length>added.quiz.correct);
const python = process.env.LERNWERKZEUG_PYTHON || 'python';
const r = spawnSync(python,['-c',lesson.code],{encoding:'utf8',env:{...process.env,PYTHONIOENCODING:'utf-8'}});
assert.equal(r.status,0,r.stderr);assert.equal(r.stdout.replace(/\r\n/g,'\n'),lesson.output);
console.log(JSON.stringify({status:'PASS',documented_lesson_id:added.id,isolated_lessons:11,local_source:true,example_output:true,application_modified:false}));
